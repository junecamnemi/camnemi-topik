/* current selected character id — persisted (localStorage cache + account sync) */
function myCharId() { return localStorage.getItem('camnemi_topik_char') || 'f-01'; }
function myChar() { return (window.CHAR_LIST || []).find(c => c.id === myCharId()) || (window.CHAR_LIST || [])[0]; }
function setMyChar(id) {
  localStorage.setItem('camnemi_topik_char', id);
  if (window.AUTH && window.AUTH.pushCharToAccount) AUTH.pushCharToAccount(id, myCharName());
  const el = $id('greet-avatar-img'); if (el) el.src = myChar().img;
  if (typeof renderAuthChip === 'function' && isAuthed && isAuthed()) renderAuthChip();
  applyCharTheme();
  render();
}
/* character display name — custom name persisted, falls back to the default */
function myCharName() {
  const custom = localStorage.getItem('camnemi_topik_char_name');
  return (custom && custom.trim()) || myChar().name;
}
function setMyCharName(n) {
  localStorage.setItem('camnemi_topik_char_name', (n || '').trim());
  if (window.AUTH && window.AUTH.pushCharToAccount) AUTH.pushCharToAccount(myCharId(), (n || '').trim());
  if (typeof renderAuthChip === 'function' && isAuthed && isAuthed()) renderAuthChip();
  render();
}
/* restore the character from the signed-in account (account is the source of truth) */
function syncCharFromAccount() {
  try {
    if (!window.AUTH || !AUTH.charFromAccount) return false;
    const acct = AUTH.charFromAccount();
    if (!acct || !acct.id) return false;
    if (!(window.CHAR_LIST || []).some(c => c.id === acct.id)) return false;
    const changed = acct.id !== myCharId() || (acct.name && acct.name !== myCharName());
    if (changed) {
      localStorage.setItem('camnemi_topik_char', acct.id);
      if (acct.name) localStorage.setItem('camnemi_topik_char_name', acct.name);
      const el = $id('greet-avatar-img'); if (el) el.src = myChar().img;
      applyCharTheme();
      render();
      return true;
    }
  } catch (e) { console.warn('char sync:', e); }
  return false;
}
/* per-character accent theme — each of the 60 chars gets a UNIQUE pastel hue.
   Index 0..59 (females 0-29, males 30-59) × golden angle 47° (coprime with 360)
   → 60 distinct hues. Char f-01 (index 0) keeps the brand violet 258°. */
function charHue(id) {
  const m = /^m-/.test(id || '');
  const n = parseInt((id || 'f-01').replace(/^[fm]-/, ''), 10) || 1;
  const idx = m ? 30 + (n - 1) : (n - 1);
  return (258 + idx * 47) % 360;
}
function applyCharTheme() {
  const hue = charHue(myCharId());
  const h2 = (hue + 38) % 360, h3 = (hue + 72) % 360;
  const root = document.documentElement;
  root.style.setProperty('--ios-blue', `hsl(${hue}, 72%, 66%)`);
  root.style.setProperty('--ios-blue-2', `hsl(${h2}, 80%, 72%)`);
  root.style.setProperty('--ios-pink', `hsl(${h3}, 82%, 72%)`);
  root.style.setProperty('--grad-brand', `linear-gradient(135deg, hsl(${hue}, 70%, 62%) 0%, hsl(${h2}, 82%, 70%) 55%, hsl(${h3}, 85%, 76%) 100%)`);
  root.style.setProperty('--grad-soft', `linear-gradient(135deg, hsla(${hue}, 80%, 65%, .12), hsla(${h3}, 85%, 75%, .16))`);
  // whole-app ambient AI backdrop — very low opacity, tinted by this character's hues
  root.style.setProperty('--ai-h1', String(hue));
  root.style.setProperty('--ai-h2', String(h2));
  root.style.setProperty('--ai-h3', String(h3));
  root.style.setProperty('--ai-a', document.documentElement.getAttribute('data-theme') === 'dark' ? '.16' : '.22');
  const mc = document.querySelector('meta[name="theme-color"]');
  if (mc) mc.setAttribute('content', `hsl(${hue}, 70%, 62%)`);
}

/* ---------- character picker sheet ---------- */
let _charTab = 'f';
function openCharPicker() {
  _charTab = myChar().g || 'f';
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (!ov || !sheet) return;
  renderCharPicker();
  ov.classList.add('show');
  sheet.classList.add('show');
  document.body.style.overflow = 'hidden';
}
function closeCharPicker() {
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (ov) ov.classList.remove('show');
  if (sheet) sheet.classList.remove('show');
  document.body.style.overflow = '';
}
function setCharTab(g) {
  _charTab = g;
  const ov = $id('char-picker');
  if (!ov) return;
  const grid = $id('char-grid');
  if (grid) grid.innerHTML = charGridHTML(g);
  ov.querySelectorAll('.ctab').forEach(b => b.classList.toggle('on', b.dataset.g === g));
}
function charGridHTML(g) {
  const cur = myCharId();
  const list = (window.CHAR_LIST || []).filter(c => c.g === g);
  return list.map(c => `
    <div class="char-cell ${c.id === cur ? 'sel' : ''}" onclick="selectChar('${c.id}')">
      <div class="char-face"><img src="${c.img}" alt="${esc(c.name)}" loading="lazy"></div>
      <span class="char-name">${esc(c.name)}</span>
    </div>`).join('');
}
function selectChar(id) {
  // selecting a character applies its default name (custom name resets to the char's own name)
  localStorage.removeItem('camnemi_topik_char_name');
  setMyChar(id);
  // close the picker and re-render — home avatar/name update immediately,
  // and the expression cycle restarts with the new character's face
  closeCharPicker();
  render();
}
function renderCharPickerHead() {
  const ov = $id('char-picker');
  if (!ov) return;
  const head = ov.querySelector('.cp-name-row');
  if (head) head.innerHTML = nameRowHTML();
  const inp = ov.querySelector('.cp-rename');
  if (inp) { inp.classList.remove('open'); inp.querySelector('input').value = myCharName(); }
}
function nameRowHTML() {
  return `
    <div class="cp-name-row">
      <span class="cp-name"><img src="${myChar().img}" alt="" class="cp-name-face"> ${esc(myCharName())}</span>
      <button class="cp-edit" onclick="toggleCharRename()">${LANG === 'ko' ? '✏️ 이름 변경' : LANG === 'km' ? '✏️ ប្តូរឈ្មោះ' : '✏️ Rename'}</button>
    </div>`;
}
function toggleCharRename() {
  const r = document.querySelector('.cp-rename');
  if (!r) return;
  r.classList.toggle('open');
  if (r.classList.contains('open')) {
    const inp = $id('cp-name-input');
    if (inp) { inp.value = myCharName(); inp.focus(); inp.select(); }
  }
}
function renderCharPicker() {
  const ov = $id('char-picker');
  if (!ov) return;
  const g = _charTab || myChar().g || 'f';
  ov.innerHTML = `
    <div class="cp-head">
      <b>${LANG === 'ko' ? '캐릭터 선택' : LANG === 'km' ? 'ជ្រើសរើសតួអង្គ' : 'Choose character'}</b>
      <span class="cp-x" onclick="closeCharPicker()">✕</span>
    </div>
    ${nameRowHTML()}
    <div class="cp-rename">
      <input id="cp-name-input" class="cp-name-input" maxlength="20" placeholder="${LANG === 'ko' ? '이름 입력…' : LANG === 'km' ? 'បញ្ចូលឈ្មោះ…' : 'Enter name…'}" value="${esc(myCharName())}">
      <button class="btn btn-primary btn-sm" onclick="saveCharName()">${LANG === 'ko' ? '저장' : LANG === 'km' ? 'រក្សាទុក' : 'Save'}</button>
    </div>
    <div class="cp-tabs">
      <button class="ctab ${g === 'f' ? 'on' : ''}" data-g="f" onclick="setCharTab('f')">👧 ${LANG === 'ko' ? '여자' : 'Female'}</button>
      <button class="ctab ${g === 'm' ? 'on' : ''}" data-g="m" onclick="setCharTab('m')">👦 ${LANG === 'ko' ? '남자' : 'Male'}</button>
    </div>
    <div class="cp-grid" id="char-grid">${charGridHTML(g)}</div>`;
}
function saveCharName() {
  const inp = $id('cp-name-input');
  if (!inp) return;
  setMyCharName(inp.value);
  toast(LANG === 'ko' ? '💖 이름이 저장됐어요!' : LANG === 'km' ? '💖 ឈ្មោះត្រូវបានរក្សាទុក!' : '💖 Name saved!');
  closeCharPicker();
  render();
}
