/* current selected character id — persisted (localStorage cache + account sync) */
function myCharId() { return localStorage.getItem('camnemi_topik_char') || 'f-01'; }
function myChar() { return (window.CHAR_LIST || []).find(c => c.id === myCharId()) || (window.CHAR_LIST || [])[0]; }
function setMyChar(id) {
  localStorage.setItem('camnemi_topik_char', id);
  if (window.AUTH && window.AUTH.pushCharToAccount) AUTH.pushCharToAccount(id, myCharName());
  const el = $id('greet-avatar-img'); if (el) el.src = myChar().img;
  if (typeof renderAuthChip === 'function' && isAuthed && isAuthed()) renderAuthChip();
  applyCharTheme();
  render();
}
/* character display name — custom name persisted, falls back to the default */
function myCharName() {
  const custom = localStorage.getItem('camnemi_topik_char_name');
  return (custom && custom.trim()) || myChar().name;
}
function setMyCharName(n) {
  localStorage.setItem('camnemi_topik_char_name', (n || '').trim());
  if (window.AUTH && window.AUTH.pushCharToAccount) AUTH.pushCharToAccount(myCharId(), (n || '').trim());
  if (typeof renderAuthChip === 'function' && isAuthed && isAuthed()) renderAuthChip();
  render();
}
/* restore the character from the signed-in account (account is the source of truth) */
function syncCharFromAccount() {
  try {
    if (!window.AUTH || !AUTH.charFromAccount) return false;
    const acct = AUTH.charFromAccount();
    if (!acct || !acct.id) return false;
    if (!(window.CHAR_LIST || []).some(c => c.id === acct.id)) return false;
    const changed = acct.id !== myCharId() || (acct.name && acct.name !== myCharName());
    if (changed) {
      localStorage.setItem('camnemi_topik_char', acct.id);
      if (acct.name) localStorage.setItem('camnemi_topik_char_name', acct.name);
      const el = $id('greet-avatar-img'); if (el) el.src = myChar().img;
      applyCharTheme();
      render();
      return true;
    }
  } catch (e) { console.warn('char sync:', e); }
  return false;
}
/* ---------- Level-based character unlocks ----------
   · Level 1–10: 3 new characters per level (L1→3, L2→6, … L10→30)
   · Level 11–40: 1 new character per level (L40 → all 60 unlocked)
   · Name can always be changed (even at L1)
   · Level 10+  : character action animations (flip-book FX) unlock
   · Level 50+  : glowing ring around the avatar
   · Level 80+  : 👑 crown on the avatar            */
function myAppLevel() {
  try { return (typeof xpLevel === 'function' && typeof xpTotal === 'function') ? xpLevel(xpTotal()) : 1; }
  catch (e) { return 1; }
}
function unlockedCharCount() {
  const lv = myAppLevel();
  if (lv <= 10) return Math.min(30, lv * 3);        // 3/level up to 30
  return Math.min(60, 30 + (lv - 10));              // +1/level → 60 at L40
}
function charUnlockLevel(id) {
  const idx = (window.CHAR_LIST || []).findIndex(c => c.id === id);
  if (idx < 0) return 1;
  return idx < 30 ? Math.ceil((idx + 1) / 3) : 10 + (idx - 29);   // f/m ordering → level needed
}
function isCharUnlocked(id) {
  const lv = myAppLevel();
  if (lv >= 40) return true;
  if (id === myCharId()) return true;               // current avatar is never locked
  const idx = (window.CHAR_LIST || []).findIndex(c => c.id === id);
  return idx >= 0 && idx < unlockedCharCount();
}
/* level gates for avatar FX */
function fxUnlocked() { return myAppLevel() >= 10; }   // action animations
function glowUnlocked() { return myAppLevel() >= 50; } // glowing ring
function crownUnlocked() { return myAppLevel() >= 80; } // 👑 crown

/* per-character accent theme — each of the 60 chars gets a UNIQUE pastel hue.
   Index 0..59 (females 0-29, males 30-59) × golden angle 47° (coprime with 360)
   → 60 distinct hues. Char f-01 (index 0) keeps the brand violet 258°. */
function charHue(id) {
  const m = /^m-/.test(id || '');
  const n = parseInt((id || 'f-01').replace(/^[fm]-/, ''), 10) || 1;
  const idx = m ? 30 + (n - 1) : (n - 1);
  return (258 + idx * 47) % 360;
}
function applyCharTheme() {
  const hue = charHue(myCharId());
  const h2 = (hue + 38) % 360, h3 = (hue + 72) % 360;
  const root = document.documentElement;
  root.style.setProperty('--ios-blue', `hsl(${hue}, 72%, 66%)`);
  root.style.setProperty('--ios-blue-2', `hsl(${h2}, 80%, 72%)`);
  root.style.setProperty('--ios-pink', `hsl(${h3}, 82%, 72%)`);
  root.style.setProperty('--grad-brand', `linear-gradient(135deg, hsl(${hue}, 72%, 54%) 0%, hsl(${h2}, 80%, 62%) 55%, hsl(${h3}, 82%, 70%) 100%)`);
  // quick cards reuse the SAME brand gradient as the session badge, angle only differs
  root.style.setProperty('--grad-a', `linear-gradient(135deg, hsl(${hue}, 72%, 54%) 0%, hsl(${h2}, 80%, 62%) 55%, hsl(${h3}, 82%, 70%) 100%)`);
  root.style.setProperty('--grad-b', `linear-gradient(45deg,  hsl(${hue}, 72%, 54%) 0%, hsl(${h2}, 80%, 62%) 55%, hsl(${h3}, 82%, 70%) 100%)`);
  root.style.setProperty('--grad-c', `linear-gradient(225deg, hsl(${hue}, 72%, 54%) 0%, hsl(${h2}, 80%, 62%) 55%, hsl(${h3}, 82%, 70%) 100%)`);
  root.style.setProperty('--grad-d', `linear-gradient(315deg, hsl(${hue}, 72%, 54%) 0%, hsl(${h2}, 80%, 62%) 55%, hsl(${h3}, 82%, 70%) 100%)`);
  root.style.setProperty('--grad-soft', `linear-gradient(135deg, hsla(${hue}, 80%, 65%, .12), hsla(${h3}, 85%, 75%, .16))`);
  // character-tinted palette for every component (cards, badges, progress…)
  root.style.setProperty('--br1', `hsl(${hue}, 72%, 60%)`);
  root.style.setProperty('--br2', `hsl(${h2}, 82%, 70%)`);
  root.style.setProperty('--br3', `hsl(${h3}, 85%, 76%)`);
  root.style.setProperty('--br-deep', `hsl(${hue}, 70%, 52%)`);
  root.style.setProperty('--br-soft', `hsla(${hue}, 80%, 65%, .13)`);
  root.style.setProperty('--br-soft2', `hsla(${h2}, 85%, 72%, .16)`);
  root.style.setProperty('--br-line', `hsla(${hue}, 80%, 62%, .28)`);
  // whole-app ambient AI backdrop — very low opacity, tinted by this character's hues
  root.style.setProperty('--ai-h1', String(hue));
  root.style.setProperty('--ai-h2', String(h2));
  root.style.setProperty('--ai-h3', String(h3));
  root.style.setProperty('--ai-a', document.documentElement.getAttribute('data-theme') === 'dark' ? '.16' : '.22');
  // quick-test 4-card palette — all derived from the character hue (harmonious)
  const q2 = (hue + 58) % 360, q3 = (hue + 116) % 360, q4 = (hue + 174) % 360;
  root.style.setProperty('--q1', String(hue));
  root.style.setProperty('--q2', String(q2));
  root.style.setProperty('--q3', String(q3));
  root.style.setProperty('--q4', String(q4));
  // readable text color on top of the brand gradient (auto contrast — dark text on light hues)
  root.style.setProperty('--on-brand', brandLuminance(hue) > 0.42 ? '#33294D' : '#FFFFFF');
  // full-bleed ambient gradient — more visible drifting AI aura
  root.style.setProperty('--ai-a2', document.documentElement.getAttribute('data-theme') === 'dark' ? '.24' : '.34');
  const mc = document.querySelector('meta[name="theme-color"]');
  if (mc) mc.setAttribute('content', `hsl(${hue}, 70%, 62%)`);
}
/* relative luminance of the brand gradient's DARKEST stop (S≈72%, L≈54%).
   Light hues (yellows/greens/cyans) get dark text; deep hues keep white. */
function brandLuminance(hue) {
  const h = ((hue % 360) + 360) % 360;
  const S = 0.72, L = 0.54;
  const C = (1 - Math.abs(2 * L - 1)) * S;
  const X = C * (1 - Math.abs((h / 60) % 2 - 1));
  const m = L - C / 2;
  let r, g, b;
  if (h < 60) [r, g, b] = [C, X, 0];
  else if (h < 120) [r, g, b] = [X, C, 0];
  else if (h < 180) [r, g, b] = [0, C, X];
  else if (h < 240) [r, g, b] = [0, X, C];
  else if (h < 300) [r, g, b] = [X, 0, C];
  else [r, g, b] = [C, 0, X];
  return 0.2126 * (r + m) + 0.7152 * (g + m) + 0.0722 * (b + m);
}

/* ---------- character picker sheet ---------- */
let _charTab = 'f';
function openCharPicker() {
  _charTab = myChar().g || 'f';
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (!ov || !sheet) return;
  renderCharPicker();
  ov.classList.add('show');
  sheet.classList.add('show');
  document.body.style.overflow = 'hidden';
}
function closeCharPicker() {
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (ov) ov.classList.remove('show');
  if (sheet) sheet.classList.remove('show');
  document.body.style.overflow = '';
}
function setCharTab(g) {
  _charTab = g;
  const ov = $id('char-picker');
  if (!ov) return;
  const grid = $id('char-grid');
  if (grid) grid.innerHTML = charGridHTML(g);
  ov.querySelectorAll('.ctab').forEach(b => b.classList.toggle('on', b.dataset.g === g));
}
function charGridHTML(g) {
  const cur = myCharId();
  const list = (window.CHAR_LIST || []).filter(c => c.g === g);
  const lv = myAppLevel();
  return list.map(c => {
    const locked = !isCharUnlocked(c.id);
    const needLv = charUnlockLevel(c.id);
    return `
    <div class="char-cell ${c.id === cur ? 'sel' : ''} ${locked ? 'locked' : ''}" ${locked ? '' : `onclick="selectChar('${c.id}')"`} title="${locked ? (LANG === 'ko' ? `Lv ${needLv}에 해제` : LANG === 'km' ? `ដោះសោនៅ Lv ${needLv}` : `Unlocks at Lv ${needLv}`) : ''}">
      <div class="char-face"><img src="${c.img}" alt="${esc(c.name)}" loading="lazy" ${locked ? 'style="filter:grayscale(1) brightness(.55);"' : ''}>
        ${locked ? `<span class="char-lock">🔒<em>Lv ${needLv}</em></span>` : ''}
        ${crownUnlocked() && c.id === cur ? '<span class="char-crown">👑</span>' : ''}
      </div>
      <span class="char-name">${esc(c.name)}</span>
    </div>`;
  }).join('');
}
function selectChar(id) {
  if (typeof isCharUnlocked === 'function' && !isCharUnlocked(id)) {
    const needLv = charUnlockLevel(id);
    toast(LANG === 'ko' ? `🔒 Lv ${needLv}에 해제돼요!` : LANG === 'km' ? `🔒 ដោះសោនៅ Lv ${needLv}!` : `🔒 Unlocks at Lv ${needLv}!`);
    return;
  }
  // selecting a character applies its default name (custom name resets to the char's own name)
  localStorage.removeItem('camnemi_topik_char_name');
  setMyChar(id);
  // close the picker and re-render — home avatar/name update immediately,
  // and the expression cycle restarts with the new character's face
  closeCharPicker();
  render();
}
function renderCharPickerHead() {
  const ov = $id('char-picker');
  if (!ov) return;
  const head = ov.querySelector('.cp-name-row');
  if (head) head.innerHTML = nameRowHTML();
  const inp = ov.querySelector('.cp-rename');
  if (inp) { inp.classList.remove('open'); inp.querySelector('input').value = myCharName(); }
}
function nameRowHTML() {
  return `
    <div class="cp-name-row">
      <span class="cp-name"><img src="${myChar().img}" alt="" class="cp-name-face"> ${esc(myCharName())}</span>
      <button class="cp-edit" onclick="toggleCharRename()">${LANG === 'ko' ? '✏️ 이름 변경' : LANG === 'km' ? '✏️ ប្តូរឈ្មោះ' : '✏️ Rename'}</button>
    </div>`;
}
function toggleCharRename() {
  const r = document.querySelector('.cp-rename');
  if (!r) return;
  r.classList.toggle('open');
  if (r.classList.contains('open')) {
    const inp = $id('cp-name-input');
    if (inp) { inp.value = myCharName(); inp.focus(); inp.select(); }
  }
}
function renderCharPicker() {
  const ov = $id('char-picker');
  if (!ov) return;
  const g = _charTab || myChar().g || 'f';
  const lv = myAppLevel();
  const unlocked = unlockedCharCount();
  const nextLv = unlocked < 60 ? (lv <= 10 ? lv + 1 : Math.min(40, lv + 1)) : null;
  const progPct = Math.min(100, Math.round(unlocked / 60 * 100));
  const statusLine = `
    <div class="cp-status">
      <span>🎮 ${LANG === 'ko' ? `내 레벨` : LANG === 'km' ? 'កម្រិតរបស់ខ្ញុំ' : 'My level'} <b>Lv ${lv}</b></span>
      <span class="cp-status-bar"><i style="width:${progPct}%"></i></span>
      <span class="cp-status-n">${unlocked}/60</span>
    </div>
    ${unlocked < 60 ? `<div class="cp-status-sub">${LANG === 'ko' ? `다음 캐릭터는 Lv ${nextLv}에 해제돼요` : LANG === 'km' ? `តួអង្គបន្ទាប់ ដោះសោនៅ Lv ${nextLv}` : `Next character unlocks at Lv ${nextLv}`}</div>` : ''}`;
  ov.innerHTML = `
    <div class="cp-head">
      <b>${LANG === 'ko' ? '캐릭터 선택' : LANG === 'km' ? 'ជ្រើសរើសតួអង្គ' : 'Choose character'}</b>
      <span class="cp-x" onclick="closeCharPicker()">✕</span>
    </div>
    ${statusLine}
    ${nameRowHTML()}
    <div class="cp-rename">
      <input id="cp-name-input" class="cp-name-input" maxlength="20" placeholder="${LANG === 'ko' ? '이름 입력…' : LANG === 'km' ? 'បញ្ចូលឈ្មោះ…' : 'Enter name…'}" value="${esc(myCharName())}">
      <button class="btn btn-primary btn-sm" onclick="saveCharName()">${LANG === 'ko' ? '저장' : LANG === 'km' ? 'រក្សាទុក' : 'Save'}</button>
    </div>
    <div class="cp-tabs">
      <button class="ctab ${g === 'f' ? 'on' : ''}" data-g="f" onclick="setCharTab('f')">👧 ${LANG === 'ko' ? '여자' : 'Female'}</button>
      <button class="ctab ${g === 'm' ? 'on' : ''}" data-g="m" onclick="setCharTab('m')">👦 ${LANG === 'ko' ? '남자' : 'Male'}</button>
    </div>
    <div class="cp-grid" id="char-grid">${charGridHTML(g)}</div>`;
}
function saveCharName() {
  const inp = $id('cp-name-input');
  if (!inp) return;
  setMyCharName(inp.value);
  toast(LANG === 'ko' ? '💖 이름이 저장됐어요!' : LANG === 'km' ? '💖 ឈ្មោះត្រូវបានរក្សាទុក!' : '💖 Name saved!');
  closeCharPicker();
  render();
}
