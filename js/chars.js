/* current selected character id — persisted */
function myCharId() { return localStorage.getItem('camnemi_topik_char') || 'f-01'; }
function myChar() { return (window.CHAR_LIST || []).find(c => c.id === myCharId()) || (window.CHAR_LIST || [])[0]; }
function setMyChar(id) {
  localStorage.setItem('camnemi_topik_char', id);
  const el = $id('greet-avatar-img'); if (el) el.src = myChar().img;
  render();
}

/* ---------- character picker sheet ---------- */
let _charTab = 'f';
function openCharPicker() {
  _charTab = myChar().g || 'f';
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (!ov || !sheet) return;
  renderCharPicker();
  ov.classList.add('show');
  sheet.classList.add('show');
  document.body.style.overflow = 'hidden';
}
function closeCharPicker() {
  const ov = $id('char-picker-overlay');
  const sheet = $id('char-picker');
  if (ov) ov.classList.remove('show');
  if (sheet) sheet.classList.remove('show');
  document.body.style.overflow = '';
}
function setCharTab(g) {
  _charTab = g;
  const ov = $id('char-picker');
  if (!ov) return;
  const grid = $id('char-grid');
  if (grid) grid.innerHTML = charGridHTML(g);
  ov.querySelectorAll('.ctab').forEach(b => b.classList.toggle('on', b.dataset.g === g));
}
function charGridHTML(g) {
  const cur = myCharId();
  const list = (window.CHAR_LIST || []).filter(c => c.g === g);
  return list.map(c => `
    <div class="char-cell ${c.id === cur ? 'sel' : ''}" onclick="selectChar('${c.id}')">
      <div class="char-face"><img src="${c.img}" alt="${esc(c.name)}" loading="lazy"></div>
      <span class="char-name">${esc(c.name)}</span>
    </div>`).join('');
}
function selectChar(id) {
  setMyChar(id);
  const g = _charTab;
  const grid = $id('char-grid');
  if (grid) grid.innerHTML = charGridHTML(g);
}
function renderCharPicker() {
  const ov = $id('char-picker');
  if (!ov) return;
  const g = _charTab || myChar().g || 'f';
  ov.innerHTML = `
    <div class="cp-head">
      <b>${LANG === 'ko' ? '캐릭터 선택' : LANG === 'km' ? 'ជ្រើសរើសតួអង្គ' : 'Choose character'}</b>
      <span class="cp-x" onclick="closeCharPicker()">✕</span>
    </div>
    <div class="cp-tabs">
      <button class="ctab ${g === 'f' ? 'on' : ''}" data-g="f" onclick="setCharTab('f')">👧 ${LANG === 'ko' ? '여자' : 'Female'}</button>
      <button class="ctab ${g === 'm' ? 'on' : ''}" data-g="m" onclick="setCharTab('m')">👦 ${LANG === 'ko' ? '남자' : 'Male'}</button>
    </div>
    <div class="cp-grid" id="char-grid">${charGridHTML(g)}</div>`;
}
